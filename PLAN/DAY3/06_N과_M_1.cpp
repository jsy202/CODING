#include <bits/stdc++.h>

using namespace std;

int visited[10];     // 숫자 사용 여부 체크
vector<int> v;       // 현재까지 뽑은 숫자 저장

void go(int n, int m, int depth)
{
    // m개를 모두 뽑았으면 정답 출력
    if(depth == m)
    {
        for(int k : v)
        {
            cout << k << ' ';
        }
        cout << "\n";

        return;
    }

    // 1 ~ n까지 모든 숫자를 후보로 확인
    for(int i = 1; i <= n; i++)
    {
        // 이미 사용한 숫자라면 다시 사용할 수 없음
        if(visited[i] == 1) continue;

        // 1. 선택
        visited[i] = 1;
        v.push_back(i);

        // 2. 다음 자리 선택하러 이동
        go(n, m, depth + 1);

        // 3. 원복
        // 다음 경우의 수를 탐색하기 위해
        // 선택했던 상태를 반드시 되돌린다.
        visited[i] = 0;
        v.pop_back();
    }
}

int main()
{
    cin.tie(nullptr);
    ios::sync_with_stdio(false);

    int n, m;
    cin >> n >> m;

    // 현재 0개를 선택한 상태에서 시작
    go(n, m, 0);
}

/*
========================================
[코테 관점 핵심]
========================================

이 문제는

"1 ~ N 중에서
중복 없이 M개를 뽑아
순서 있게 나열"

하는 문제.

즉, 순열(Permutation) 문제이다.


========================================
[백트래킹 핵심 구조]
========================================

백트래킹 문제는 대부분 아래 구조로 간다.

void go(...)
{
    // 1. 종료조건
    if(정답 조건)
    {
        정답 처리;
        return;
    }

    // 2. 가능한 후보 모두 확인
    for(...)
    {
        if(사용 불가능) continue;

        // 선택
        상태 변경;

        // 다음 단계
        go(...);

        // 원복
        상태 복구;
    }
}


즉 외울 것:

선택
-> 재귀
-> 원복


========================================
[왜 visited가 필요한가?]
========================================

예를 들어

N = 4, M = 2

에서

1 2

를 만들었다면

다음 자리에서 1을 또 선택하면

1 1

이 되어버린다.

하지만 이 문제는 중복 선택 불가능.

그래서

visited[i]

를 사용해서

"현재 경로에서 이미 사용한 숫자인가?"

를 체크한다.


========================================
[왜 원복해야 하는가?]
========================================

예를 들어

1 -> 2

를 탐색한 뒤에는

다음 경우

1 -> 3

도 탐색해야 한다.

따라서

visited[2] = 1

상태를 계속 유지하면 안 된다.

재귀가 끝난 후

visited[2] = 0;

으로 되돌려야 다음 경우의 수를 탐색할 수 있다.


vector도 마찬가지.

v.push_back(i);

했으면

재귀가 끝난 후

v.pop_back();

해서 이전 상태로 되돌린다.


========================================
[depth의 의미]
========================================

depth = 현재까지 몇 개를 뽑았는가

처음:
depth = 0

숫자 하나 선택:
depth = 1

숫자 두 개 선택:
depth = 2

...

depth == m
-> M개를 모두 선택
-> 정답 완성


========================================
[이 문제에서 외워야 하는 템플릿]
========================================

void go(int depth)
{
    if(depth == m)
    {
        // 정답 처리
        return;
    }

    for(int i = 1; i <= n; i++)
    {
        if(visited[i]) continue;

        visited[i] = 1;
        v.push_back(i);

        go(depth + 1);

        visited[i] = 0;
        v.pop_back();
    }
}


이 구조는 코테에서 매우 중요.

특히 아래 문제에 그대로 적용된다.

- 순열
- 모든 경우의 수 만들기
- 숫자 중복 없이 선택
- 사람 배치
- 작업 순서 만들기
- 연산 순서 탐색
- 경로 후보 탐색
- 백트래킹


========================================
[문제 읽고 이 구조를 떠올리는 신호]
========================================

문제에서 이런 말 나오면 의심:

"모든 경우"
"순서를 정한다"
"M개를 선택한다"
"중복 없이"
"가능한 모든 조합"
"배치한다"

그리고 N이 작다.

-> 완전탐색 / 백트래킹 의심


========================================
[시간복잡도]
========================================

N개 중 중복 없이 M개를 순서 있게 뽑음.

경우의 수:

N P M

= N! / (N-M)!

최악 M = N이면

O(N!)

따라서 이런 순열 백트래킹은
N이 작을 때 사용하는 방식이다.


========================================
[진짜 외워야 할 한 줄]
========================================

백트래킹 = 선택 -> 재귀 -> 원복

visited[i] = 1;
v.push_back(i);

go(...);

visited[i] = 0;
v.pop_back();

이 덩어리는 그냥 외워도 됨.
========================================
*/
