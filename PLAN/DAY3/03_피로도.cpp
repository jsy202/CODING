#include <string>
#include <vector>
#include <algorithm>

using namespace std;

int mx = 0;
int visited[10];

void go(int k, const vector<vector<int>>& v, int cnt)
{
    // 지금까지 방문한 던전 수 중 최댓값 갱신
    mx = max(mx, cnt);

    // 현재 상태에서 갈 수 있는 모든 던전을 확인
    for(int i = 0; i < v.size(); i++)
    {
        // 이미 방문한 던전은 다시 방문하면 안 됨
        if(visited[i]) continue;

        // 현재 피로도가 최소 필요 피로도 이상이라면 입장 가능
        if(k >= v[i][0])
        {
            // 선택
            visited[i] = 1;

            // 해당 던전을 방문한 뒤 다음 경우 탐색
            go(k - v[i][1], v, cnt + 1);

            // 원복
            visited[i] = 0;
        }
    }
}

int solution(int k, vector<vector<int>> dungeons)
{
    mx = 0;

    go(k, dungeons, 0);

    return mx;
}


/*
[이 문제에서 배워야 할 핵심]

1. 이 문제는 "던전 방문 순서"를 전부 시험해보는 완전탐색/백트래킹 문제다.

   핵심 질문은:

   "현재 피로도로 아직 방문하지 않은 던전 중
    어떤 던전을 다음으로 갈 것인가?"

   따라서 매 단계마다

   for(int i = 0; i < v.size(); i++)

   로 가능한 모든 선택지를 확인한다.


2. 이 문제는 앞의 부분수열 문제와 DFS 구조가 다르다.

   부분수열 문제:
   -> 현재 원소를 선택 / 미선택
   -> 선택지가 항상 2개

   피로도 문제:
   -> 아직 방문하지 않은 던전 중 하나를 선택
   -> 선택지가 상황에 따라 여러 개

   즉 DFS 문제라고 전부 같은 모양이 아니다.

   항상 먼저
   "현재 상태에서 가능한 선택지가 몇 개인가?"
   를 생각해야 한다.


3. 이 문제에서는 visited가 필요하다.

   던전을 한 번 방문하면
   같은 탐색 경로 안에서는 다시 방문하면 안 된다.

   예를 들어

   0번 던전 -> 1번 던전 -> 0번 던전

   같은 중복 방문을 막아야 하므로

   if(visited[i]) continue;

   를 사용한다.


4. visited는 "현재 DFS 경로에서 선택된 던전"을 의미한다.

   던전을 선택할 때:

   visited[i] = 1;

   재귀가 끝나고 돌아왔을 때:

   visited[i] = 0;

   로 반드시 원복해야 한다.

   이 구조가 백트래킹의 핵심이다.


   선택
   ↓
   visited[i] = 1
   ↓
   재귀 호출
   ↓
   돌아옴
   ↓
   visited[i] = 0
   ↓
   다른 선택 시도


5. 왜 visited를 다시 0으로 바꿔야 하는가?

   예를 들어 던전이

   A, B, C

   라면

   A -> B -> C

   순서도 확인해야 하지만

   A -> C -> B

   순서도 확인해야 한다.

   만약 B 방문 후 visited[B]를 원복하지 않으면
   다른 순서를 탐색할 때 B를 다시 선택할 수 없다.

   즉 원복은

   "방금 선택을 취소하고 다른 경우를 시험한다"

   는 뜻이다.


6. 재귀 함수의 매개변수 의미를 명확하게 잡는다.

   go(k, v, cnt)

   k
   = 현재 남아 있는 피로도

   v
   = 던전 정보

   cnt
   = 지금까지 방문한 던전 개수

   visited
   = 현재 경로에서 이미 방문한 던전


7. 이 문제는 종료조건을 따로 작성하지 않아도 된다.

   일반적인 DFS에서는

   if(...)
   {
       ...
       return;
   }

   같은 종료조건을 많이 사용한다.

   하지만 이 문제는 더 이상 갈 수 있는 던전이 없으면
   for문 안에서 재귀 호출이 발생하지 않는다.

   그러면 함수가 자연스럽게 끝난다.

   즉

   "선택 가능한 다음 상태가 없으면 자동 종료"

   구조이다.


8. 그래서 매 재귀 호출마다

   mx = max(mx, cnt);

   를 수행한다.

   탐색이 어디에서 끝날지 모르기 때문에
   현재까지 방문한 던전 수를 계속 최댓값과 비교한다.


9. 던전 입장 조건과 실제 소모 피로도를 구분해야 한다.

   v[i][0]
   = 최소 필요 피로도

   v[i][1]
   = 소모 피로도

   따라서 입장 가능 여부는

   if(k >= v[i][0])

   이고,

   실제 다음 피로도는

   k - v[i][1]

   이다.

   둘을 헷갈리면 안 된다.


10. 이 문제에서 백트래킹 구조를 한 줄로 외우면

    for(모든 선택지)
    {
        if(선택 불가능) continue;

        선택 처리;
        dfs(다음 상태);
        선택 원복;
    }

    실제 코드로 보면

    for(int i = 0; i < v.size(); i++)
    {
        if(visited[i]) continue;

        if(k >= v[i][0])
        {
            visited[i] = 1;

            go(k - v[i][1], v, cnt + 1);

            visited[i] = 0;
        }
    }


11. 완전탐색/백트래킹 문제를 만나면 먼저 아래 4개를 생각한다.

    [1] 현재 상태는 무엇인가?
        -> 현재 피로도 k
        -> 방문한 던전 수 cnt
        -> visited

    [2] 현재 상태에서 가능한 선택은 무엇인가?
        -> 아직 방문하지 않았고
           현재 피로도로 입장 가능한 던전 하나 선택

    [3] 선택했을 때 무엇이 바뀌는가?
        -> visited[i] = 1
        -> k -= 소모 피로도
        -> cnt + 1

    [4] 재귀가 끝난 뒤 무엇을 원복해야 하는가?
        -> visited[i] = 0


12. 앞의 부분수열 문제와 비교해서 기억하면 좋다.

    [부분수열]
    각 원소마다
    선택 / 미선택

    go(idx + 1, ...)
    go(idx + 1, ...)

    visited 필요 X


    [피로도]
    아직 안 간 던전 중
    다음 던전 하나 선택

    for문으로 모든 던전 확인

    visited 필요 O
    재귀 후 원복 필요 O


[시험장에서 기억할 한 문장]

"순서를 바꿔가며 모든 경우를 봐야 하고,
같은 대상을 한 경로에서 두 번 쓰면 안 된다"

-> for문 + visited + 선택 + 재귀 + 원복
*/
