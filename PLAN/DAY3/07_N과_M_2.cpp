#include <bits/stdc++.h>

using namespace std;

vector<int> pick;

void go(int n, int m, int start)
{
    // m개를 모두 골랐으면 정답 출력
    if(pick.size() == m)
    {
        for(int x : pick)
        {
            cout << x << ' ';
        }
        cout << "\n";

        return;
    }

    // start부터 n까지 후보를 확인
    for(int i = start; i <= n; i++)
    {
        // 1. 선택
        pick.push_back(i);

        // 2. 다음 숫자는 i보다 큰 숫자만 선택
        // i+1부터 시작
        go(n, m, i + 1);

        // 3. 원복
        pick.pop_back();
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int m, n;
    cin >> n >> m;

    // 처음에는 1부터 선택 가능
    go(n, m, 1);

    return 0;
}

