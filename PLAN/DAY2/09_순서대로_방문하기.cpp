#include <iostream>
#include <vector>

using namespace std;

int ret = 0;                    // 정답: 조건을 만족하는 경로의 개수
int n, m;

vector<vector<int>> grid;       // 격자
vector<pair<int, int>> points;  // 반드시 순서대로 방문해야 하는 지점들

// 위 → 오른쪽 → 아래 → 왼쪽
int dy[] = {-1, 0, 1, 0};
int dx[] = {0, 1, 0, -1};

int visited[10][10];            // 현재 경로에서 방문했는지 표시


void dfs(int y, int x, int idx)
{
    /*
        idx의 의미
        -------------------------
        지금 몇 번째 목적지를 찾아가고 있는가?

        points[0] = 시작점
        points[1] = 다음 목적지
        points[2] = 그 다음 목적지
        ...

        예)
        idx == 1
        → 현재 points[1]을 찾아가는 중
    */


    // 현재 위치가 지금 찾아야 하는 목적지라면
    if(y == points[idx].first && x == points[idx].second)
    {
        // 마지막 목적지까지 도착했다면
        if(idx == m - 1)
        {
            ret++;      // 가능한 경로 하나 발견
            return;
        }

        // 아직 목적지가 남았다면
        // 다음 목적지를 찾아간다.
        idx++;
    }


    // 현재 위치에서 상하좌우 4방향 탐색
    for(int i = 0; i < 4; i++)
    {
        int ny = y + dy[i];
        int nx = x + dx[i];


        // 1. 격자 밖이면 못 감
        if(ny < 0 || ny >= n || nx < 0 || nx >= n)
            continue;


        // 2. 이미 현재 경로에서 방문했거나
        //    1(벽)인 곳이면 못 감
        if(visited[ny][nx] || grid[ny][nx] == 1)
            continue;


        // =========================
        // 백트래킹 핵심 구조
        // =========================

        // 선택
        visited[ny][nx] = 1;

        // 해당 칸으로 이동해서 계속 탐색
        dfs(ny, nx, idx);

        // 원복
        // 다른 경로에서는 이 칸을 다시 사용할 수 있어야 함
        visited[ny][nx] = 0;
    }
}


int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n >> m;


    // n x n 격자 생성
    grid.resize(n, vector<int>(n));

    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < n; j++)
        {
            cin >> grid[i][j];
        }
    }


    // 반드시 방문해야 하는 지점 입력
    points.resize(m);

    for(int i = 0; i < m; i++)
    {
        int y, x;
        cin >> y >> x;

        // 문제 입력은 1부터 시작
        // 배열은 0부터 시작하므로 -1
        points[i] = {y - 1, x - 1};
    }


    // 시작점은 이미 밟고 시작한다.
    visited[points[0].first][points[0].second] = 1;


    // points[0]은 시작점이므로
    // 이제 points[1]부터 찾아간다.
    dfs(points[0].first, points[0].second, 1);


    cout << ret << '\n';

    return 0;
}


